export function productCopy(product: Product, locale: "en" | "id") {
  if (locale !== "id") {
    return {
      summary: product.summary,
      description: product.description,
      imageAlt: product.imageAlt,
    };
  }
  const copy = productIdCopy[product.id];
  return {
    summary: copy?.summary ?? product.summary,
    description: copy?.description ?? product.description,
    imageAlt: copy?.imageAlt ?? product.imageAlt,
  };
}
